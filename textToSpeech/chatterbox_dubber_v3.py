def find_speaker_reference(
    speaker: str,
    speaker_dir: Path,
    reference_dir: Path,
    reference_seconds: float,
    threshold_db: float,
) -> Path:
    """
    Build a short WAV reference from speaker_pipeline.py's concatenated track.

    Existing manually-created <Speaker>.*.wav in reference_dir wins over the
    automatically-created reference, so the user can override a bad sample.
    """
    reference_dir.mkdir(parents=True, exist_ok=True)

    safe = safe_filename(speaker)
    manual_candidates = [
        reference_dir / f"{safe}.wav",
        reference_dir / f"{safe}_ref.wav",
        reference_dir / f"{speaker}.wav",
    ]
    for candidate in manual_candidates:
        if candidate.exists():
            return candidate

    source_candidates = [
        speaker_dir / f"{safe}.mp3",
        speaker_dir / f"{safe}.wav",
        speaker_dir / f"{speaker}.mp3",
        speaker_dir / f"{speaker}.wav",
    ]

    source = next((p for p in source_candidates if p.exists()), None)
    if source is None:
        raise FileNotFoundError(
            f"No speaker sample found for {speaker!r} in {speaker_dir}"
        )

    output = reference_dir / f"{safe}_ref.wav"

    # Convert to 16 kHz mono, remove leading/trailing silence, then cap length.
    # Chatterbox performs its own conditioning, but a clean short prompt is much
    # more practical than passing the entire concatenated speaker track each time.
    audio_filter = (
        f"atrim=0:{reference_seconds:.3f},"
        f"silenceremove="
        f"start_periods=1:start_duration=0.15:start_threshold={threshold_db}dB:"
        f"stop_periods=-1:stop_duration=0.30:stop_threshold={threshold_db}dB," #was stop_periods = 1
        f"asetpts=N/SR/TB"
    )

    run_cmd(
        [
            "ffmpeg",
            "-y",
            "-i",
            str(source),
            "-vn",
            "-ac",
            "1",
            "-ar",
            "16000",
            "-af",
            audio_filter,
            "-c:a",
            "pcm_s16le",
            "-loglevel",
            "error",
            str(output),
        ]
    )

    if not output.exists() or ffprobe_duration(output) < 2: #was 0.25 instead of 2.0
        print(f"WARNING: Auto-generated reference for {speaker} is too short. "
              f"Using simple cut instead.")
        # Fall back to a simple 12s cut in case a particular FFmpeg build does
        # not remove silence as expected.
        run_cmd(
            [
                "ffmpeg",
                "-y",
                "-i",
                str(source),
                "-vn",
                "-ac",
                "1",
                "-ar",
                "16000",
                "-t",
                f"{reference_seconds:.3f}",
                "-c:a",
                "pcm_s16le",
                "-loglevel",
                "error",
                str(output),
            ]
        )

    return output


# ---------------------------------------------------------------------------
# Text splitting for TTS
# ---------------------------------------------------------------------------

def split_tts_text(text: str, max_chars: int) -> list[str]:
    """
    Keep individual Chatterbox requests reasonably short.

    Split first on sentence punctuation, then on commas/spaces if a sentence
    is still too long. This is only a TTS input split; subtitle timing remains
    one single cue window.
    """
    text = normalize_text(text)
    if len(text) <= max_chars:
        return [text]

    sentence_parts = re.split(r"(?<=[.!?…])\s+", text)
    chunks: list[str] = []
    current = ""

    for part in sentence_parts:
        part = part.strip()
        if not part:
            continue

        if not current:
            current = part
            continue

        candidate = current + " " + part
        if len(candidate) <= max_chars:
            current = candidate
        else:
            chunks.append(current)
            current = part

    if current:
        chunks.append(current)

    # A single sentence can still exceed the limit. Split it by clause/word.
    final_chunks: list[str] = []
    for chunk in chunks:
        if len(chunk) <= max_chars:
            final_chunks.append(chunk)
            continue

        clause_parts = re.split(r"(?<=[,;:—-])\s+", chunk)
        current = ""
        for part in clause_parts:
            part = part.strip()
            if not part:
                continue

            if not current:
                current = part
                continue

            candidate = current + " " + part
            if len(candidate) <= max_chars:
                current = candidate
            else:
                final_chunks.append(current)
                current = part

        if current:
            # Last resort: hard word boundary split.
            if len(current) <= max_chars:
                final_chunks.append(current)
            else:
                words = current.split()
                piece = ""
                for word in words:
                    candidate = word if not piece else piece + " " + word
                    if len(candidate) <= max_chars:
                        piece = candidate
                    else:
                        if piece:
                            final_chunks.append(piece)
                        piece = word
                if piece:
                    final_chunks.append(piece)

    return final_chunks or [text]


