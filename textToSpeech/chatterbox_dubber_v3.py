class ChatterboxSpeaker:
    def __init__(
        self,
        device: str,
        exaggeration: float,
        cfg_weight: float,
        temperature: float,
        min_p: float,
        top_p: float,
        repetition_penalty: float,
        seed: int,
        t3_model: str = DEFAULT_T3_MODEL,
        tts_retries: int = DEFAULT_TTS_RETRIES,
        min_duration_ratio: float = DEFAULT_MIN_DURATION_RATIO,
    ):
        self.device = device
        self.exaggeration = exaggeration
        self.cfg_weight = cfg_weight
        self.temperature = temperature
        self.min_p = min_p
        self.top_p = top_p
        self.repetition_penalty = repetition_penalty
        self.seed = seed
        self.requested_t3_model = t3_model
        self.tts_retries = max(1, int(tts_retries))
        self.min_duration_ratio = max(0.1, float(min_duration_ratio))
        self.expected_chars_per_second = DEFAULT_EXPECTED_CHARS_PER_SECOND

        print(f"Loading Chatterbox Multilingual TTS on {device}...")
        self.model, self.t3_model = self._load_model(device, t3_model)
        if hasattr(self.model, "eval"):
            self.model.eval()
        print(f"Using multilingual T3 model: {self.t3_model}")

        self.current_reference: Path | None = None
        self.cache: dict[str, Path] = {}

    def _load_model(self, device: str, requested: str):
        """Load V3 when available, otherwise safely fall back to V2."""
        requested = (requested or DEFAULT_T3_MODEL).lower()

        if requested not in {"auto", "v2", "v3"}:
            raise ValueError("--t3-model must be one of: auto, v2, v3")

        supports_t3_model = "t3_model" in inspect.signature(
            ChatterboxMultilingualTTS.from_pretrained
        ).parameters

        if requested in {"auto", "v3"} and supports_t3_model:
            try:
                model = ChatterboxMultilingualTTS.from_pretrained(
                    device=device,
                    t3_model="v3",
                )
                return model, "v3"
            except Exception as exc:
                if requested == "v3":
                    raise RuntimeError(
                        "Requested Chatterbox Multilingual V3, but it could not "
                        f"be loaded: {type(exc).__name__}: {exc}"
                    ) from exc

                print(
                    "WARNING: Multilingual V3 could not be loaded; "
                    f"falling back to V2. Reason: {type(exc).__name__}: {exc}"
                )

        if requested == "v3" and not supports_t3_model:
            raise RuntimeError(
                "The installed Chatterbox package does not support t3_model='v3'. "
                "Your installation is probably the PyPI 0.1.7 line. "
                "Install the current GitHub version to use V3, or run with "
                "--t3-model v2."
            )

        model = ChatterboxMultilingualTTS.from_pretrained(device=device)
        return model, "v2"

    def prepare_reference(self, reference_path: Path) -> None:
        reference_path = reference_path.resolve()

        if self.current_reference == reference_path:
            return

        print(f"Preparing voice reference: {reference_path}")
        self.model.prepare_conditionals(
            str(reference_path),
            exaggeration=self.exaggeration,
        )
        self.current_reference = reference_path

    def _expected_duration(self, text: str) -> float:
        """Conservative speech-duration estimate used only to reject obvious truncation."""
        compact = re.sub(r"\s+", "", text)
        char_count = max(1, len(compact))
        return max(0.45, char_count / self.expected_chars_per_second)

    def _duration_is_plausible(self, text: str, duration: float) -> bool:
        expected = self._expected_duration(text)
        
        min_duration = max(0.45, expected * self.min_duration_ratio)
    
        # НОВОЕ: проверяем максимальную длительность
        # Если аудио больше 5x от ожидаемого, это артефакт
        max_duration = max(5.0, expected * 5)  # минимум 5 секунд или 5x от ожидаемого
        
        if duration > max_duration:
            print(
                f"      WARNING: Generated duration {duration:.3f}s is too long "
                f"(expected ~{expected:.3f}s, max allowed {max_duration:.3f}s). "
                f"Treating as artifact."
            )
            return False
        
        return duration >= min_duration

    def _generation_attempts(self):
        """Return progressively safer sampler settings for early-EOS recovery."""
        attempts = [
            {
                "temperature": self.temperature,
                "min_p": self.min_p,
                "top_p": self.top_p,
                "repetition_penalty": self.repetition_penalty,
                "exaggeration": self.exaggeration,
            }
        ]

        if self.tts_retries >= 2:
            # Lower temperature/repetition pressure and a slightly lower
            # exaggeration make V2 less eager to fall into repetition/EOS loops.
            attempts.append(
                {
                    "temperature": min(self.temperature, 0.65),
                    "min_p": min(self.min_p, 0.02),
                    "top_p": self.top_p,
                    "repetition_penalty": min(self.repetition_penalty, 1.08),
                    "exaggeration": min(self.exaggeration, 0.40),
                }
            )

        if self.tts_retries >= 3:
            # Very conservative fallback. Keep cfg_weight unchanged because 0
            # is deliberately used for cross-language Russian generation.
            attempts.append(
                {
                    "temperature": 0.60,
                    "min_p": 0.0,
                    "top_p": 1.0,
                    "repetition_penalty": 1.0,
                    "exaggeration": 0.35,
                }
            )

        return attempts[: min(self.tts_retries, len(attempts))]

    def _generate_one_part(
        self,
        part: str,
        part_index: int,
        total_parts: int,
    ):
        """Generate one part, retrying when an obvious early EOS is detected."""
        candidates = []

        for attempt_index, params in enumerate(self._generation_attempts(), start=1):
            if self.seed:
                set_global_seed(self.seed + part_index + (attempt_index - 1) * 1000)

            print(
                f"    TTS {part_index + 1}/{total_parts}, attempt {attempt_index}/"
                f"{min(self.tts_retries, 3)}: {part[:90]!r}"
            )

            try:
                wav = self.model.generate(
                    part,
                    language_id=LANGUAGE_ID,
                    exaggeration=params["exaggeration"],
                    cfg_weight=self.cfg_weight,
                    temperature=params["temperature"],
                    min_p=params["min_p"],
                    top_p=params["top_p"],
                    repetition_penalty=params["repetition_penalty"],
                )
            except Exception as exc:
                error_msg = str(exc)
                # Ловим CUDA-ошибки и out-of-range
                if ("CUDA" in error_msg or 
                    "illegal memory access" in error_msg or 
                    "out-of-range" in error_msg or
                    "srcIndex" in error_msg):
                    print(
                        f"      CRITICAL CUDA/FLOW error on attempt {attempt_index}: {error_msg[:200]}"
                    )
                    print("      Resetting CUDA state and retrying...")
                    # Агрессивная очистка памяти
                    gc.collect()
                    if torch.cuda.is_available():
                        torch.cuda.empty_cache()
                        try:
                            torch.cuda.synchronize()
                        except RuntimeError:
                            print("      CUDA context corrupted, continuing anyway...")
                    continue
                else:
                    print(
                        f"      Generation error on attempt {attempt_index}: "
                        f"{type(exc).__name__}: {exc}"
                    )
                    gc.collect()
                    if torch.cuda.is_available():
                        torch.cuda.empty_cache()
                    continue
            except Exception as exc:
                print(
                    f"      Generation error on attempt {attempt_index}: "
                    f"{type(exc).__name__}: {exc}"
                )
                gc.collect()
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()
                continue

            if isinstance(wav, torch.Tensor):
                wav_tensor = wav.detach().cpu()
            else:
                wav_tensor = torch.as_tensor(wav).cpu()

            if wav_tensor.ndim == 1:
                wav_tensor = wav_tensor.unsqueeze(0)
            elif wav_tensor.ndim > 2:
                wav_tensor = wav_tensor.squeeze()
                if wav_tensor.ndim == 1:
                    wav_tensor = wav_tensor.unsqueeze(0)

            duration = int(wav_tensor.shape[-1]) / float(self.model.sr)
            if duration <= 0.01:
                continue

            plausible = self._duration_is_plausible(part, duration)
            print(
                f"      Generated duration: {duration:.3f}s "
                f"({'plausible' if plausible else 'TOO SHORT/LONG'})"
            )
            candidates.append((wav_tensor, duration, plausible, attempt_index))

            # Once we have a plausible result, do not spend more time generating
            # alternatives. The retries are primarily for the early-EOS failure.
            if plausible:
                break

            # Free the unsuccessful tensor before retrying.
            del wav_tensor
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()

        if not candidates:
            raise RuntimeError("Chatterbox returned no usable waveform after retries.")

        # Prefer the first plausible result. If all attempts were too short,
        # choose the longest one: it is generally less truncated than the others.
        plausible_candidates = [item for item in candidates if item[2]]
        if plausible_candidates:
            chosen = plausible_candidates[0]
        else:
            # Do not turn an entire subtitle into silence just because the
            # conservative heuristic rejected every attempt. Keep the longest
            # generated candidate and make the problem visible in the log.
            chosen = max(candidates, key=lambda item: item[1])
            expected = self._expected_duration(part)
            print(
                f"      WARNING: all attempts were shorter than the safety "
                f"threshold. Using longest={chosen[1]:.3f}s; estimated="
                f"{expected:.3f}s."
            )

        return chosen[0], chosen[1]

    def generate_to_file(
        self,
        text: str,
        reference_path: Path,
        output_path: Path,
        max_chars: int,
        interpart_pause: float,
    ) -> tuple[Path, float]:
        """Generate a cue into WAV and return (path, duration_seconds)."""
        self.prepare_reference(reference_path)

        cache_key = hashlib.sha256(
            (
                str(reference_path.resolve())
                + "\0"
                + text
                + "\0"
                + str(self.seed)
                + "\0"
                + str(self.exaggeration)
                + "\0"
                + str(self.cfg_weight)
                + "\0"
                + str(self.temperature)
                + "\0"
                + str(self.min_p)
                + "\0"
                + str(self.top_p)
                + "\0"
                + str(self.repetition_penalty)
                + "\0"
                + str(self.t3_model)
                + "\0"
                + str(self.tts_retries)
                + "\0"
                + str(self.min_duration_ratio)
            ).encode("utf-8")
        ).hexdigest()

        if cache_key in self.cache and self.cache[cache_key].exists():
            try:
                duration = ffprobe_duration(self.cache[cache_key])
            except Exception:
                duration = 0.0
            if duration > 0.01:
                shutil.copy2(self.cache[cache_key], output_path)
                return output_path, duration
            self.cache.pop(cache_key, None)

        parts = split_tts_text(text, max_chars=max_chars)
        part_paths: list[Path] = []
        part_durations: list[float] = []

        with tempfile.TemporaryDirectory(prefix="chatterbox_parts_") as temp_dir:
            temp_dir_path = Path(temp_dir)

            for i, part in enumerate(parts):
                wav_tensor, generated_duration = self._generate_one_part(
                    part=part,
                    part_index=i,
                    total_parts=len(parts),
                )

                part_path = temp_dir_path / f"part_{i:03d}.wav"
                ta.save(
                    str(part_path),
                    wav_tensor.float(),
                    self.model.sr,
                )
                part_paths.append(part_path)
                part_durations.append(generated_duration)
                del wav_tensor
                gc.collect()
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()

            if len(part_paths) == 1:
                # Do NOT aggressively silenceremove the generated speech here:
                # low-level final phonemes can be clipped. We only normalize
                # sample rate/channel and leave the waveform intact.
                run_cmd(
                    [
                        "ffmpeg",
                        "-y",
                        "-i",
                        str(part_paths[0]),
                        "-vn",
                        "-ac",
                        "1",
                        "-ar",
                        str(DEFAULT_SAMPLE_RATE),
                        "-c:a",
                        "pcm_s16le",
                        "-loglevel",
                        "error",
                        str(output_path),
                    ]
                )
            else:
                # For long text, concatenate TTS parts without inserting an
                # artificial pause. Splitting is purely to keep each model call
                # stable; the final cue still gets fitted to one subtitle window.
                concat_list = temp_dir_path / "parts.txt"
                with concat_list.open("w", encoding="utf-8") as f:
                    for part_path in part_paths:
                        safe = str(part_path).replace("'", "'\\''")
                        f.write(f"file '{safe}'\n")

                run_cmd(
                    [
                        "ffmpeg",
                        "-y",
                        "-f",
                        "concat",
                        "-safe",
                        "0",
                        "-i",
                        str(concat_list),
                        "-ac",
                        "1",
                        "-ar",
                        str(DEFAULT_SAMPLE_RATE),
                        "-c:a",
                        "pcm_s16le",
                        "-loglevel",
                        "error",
                        str(output_path),
                    ]
                )

        # Prefer the exact duration obtained from the TTS tensors. It avoids the
        # old ffprobe=N/A failure for freshly-created WAV files.
        final_duration = sum(part_durations)

        cache_dir = output_path.parent / ".tts_cache"
        cache_dir.mkdir(parents=True, exist_ok=True)
        cache_path = cache_dir / f"{cache_key}.wav"
        shutil.copy2(output_path, cache_path)
        self.cache[cache_key] = cache_path
        return output_path, final_duration


