"""
chatterbox_dubber.py

Local Russian dubbing pipeline for an SRT produced by the speaker pipeline.

Input:
  - original audio/video
  - translated/compressed SRT with [Speaker N]: text
  - speaker_outputs/Speaker_N.mp3 (generated by speaker_pipeline.py)

Output:
  - a Russian speech-only audio track with the same duration as the source
  - optionally a video with the new track muxed in

The original speaker_pipeline.py is NOT modified by this program.

Important timing behavior:
  * Each subtitle cue defines an allowed speech window.
  * If synthesized speech is shorter than the cue window, it is centered:
        cue_start + (cue_duration - speech_duration) / 2
  * If synthesized speech is longer than the cue window, FFmpeg's atempo is
    used to fit it into the window while preserving pitch as much as possible.
  * Each cue becomes an exact-duration audio segment. Speaker tracks are then
    concatenated onto the global timeline and mixed with one another.
  * For freshly generated WAV files, duration is known directly from the Chatterbox
    waveform tensor, avoiding the ffprobe=N/A failure mode.
  * Failed individual cues are logged and replaced with exact-duration silence so
    a long dubbing job can continue.

Background/dialogue replacement:
  This script intentionally creates a CLEAN Russian speech track. It does not
  claim to remove original dialogue from the source. See the notes printed by
  --help / final output for the limitation and the optional preview mix.
"""

