def make_speaker_track(
    speaker: str,
    cues: list[Cue],
    cue_files: dict[int, Path],
    total_duration: float,
    speaker_output_dir: Path,
) -> Path:
    """
    Create one full-duration speaker track from fixed-duration cue files.

    Cue files already have exact subtitle-window durations. We concatenate them
    with correctly sized silence gaps so the result is aligned to the source.
    """
    speaker_output_dir.mkdir(parents=True, exist_ok=True)

    speaker_path = speaker_output_dir / f"{safe_filename(speaker)}_dub.wav"

    ordered = sorted(cues, key=lambda c: (c.start, c.end, c.index))

    with tempfile.TemporaryDirectory(prefix="speaker_timeline_") as temp_dir:
        temp = Path(temp_dir)
        silence_cache: dict[int, Path] = {}
        sequence: list[Path] = []
        cursor = 0.0

        for cue in ordered:
            if cue.start < cursor - 0.005:
                print(
                    f"  WARNING: overlapping cues for {speaker}: "
                    f"{cue.start:.3f} < {cursor:.3f}."
                )

            gap = max(0.0, cue.start - cursor)
            if gap > 0.005:
                gap_ms = int(round(gap * 1000))
                if gap_ms not in silence_cache:
                    silence_path = temp / f"silence_{gap_ms}.wav"
                    run_cmd(
                        [
                            "ffmpeg",
                            "-y",
                            "-f",
                            "lavfi",
                            "-i",
                            f"anullsrc=channel_layout=mono:sample_rate={DEFAULT_SAMPLE_RATE}",
                            "-t",
                            f"{gap:.6f}",
                            "-c:a",
                            "pcm_s16le",
                            "-loglevel",
                            "error",
                            str(silence_path),
                        ]
                    )
                    silence_cache[gap_ms] = silence_path

                sequence.append(silence_cache[gap_ms])

            sequence.append(cue_files[cue.index])
            cursor = max(cursor, cue.end)

        tail = max(0.0, total_duration - cursor)
        if tail > 0.005:
            tail_ms = int(round(tail * 1000))
            if tail_ms not in silence_cache:
                silence_path = temp / f"silence_tail_{tail_ms}.wav"
                run_cmd(
                    [
                        "ffmpeg",
                        "-y",
                        "-f",
                        "lavfi",
                        "-i",
                        f"anullsrc=channel_layout=mono:sample_rate={DEFAULT_SAMPLE_RATE}",
                        "-t",
                        f"{tail:.6f}",
                        "-c:a",
                        "pcm_s16le",
                        "-loglevel",
                        "error",
                        str(silence_path),
                    ]
                )
                silence_cache[tail_ms] = silence_path
            sequence.append(silence_cache[tail_ms])

        if not sequence:
            raise RuntimeError(f"No timeline segments for {speaker}")

        concat_list = temp / "concat.txt"
        with concat_list.open("w", encoding="utf-8") as f:
            for item in sequence:
                safe = str(item).replace("'", "'\\''")
                f.write(f"file '{safe}'\n")

        run_cmd(
            [
                "ffmpeg",
                "-y",
                "-f",
                "concat",
                "-safe",
                "0",
                "-i",
                str(concat_list),
                "-ac",
                "1",
                "-ar",
                str(DEFAULT_SAMPLE_RATE),
                "-c:a",
                "pcm_s16le",
                "-t",
                f"{total_duration:.6f}",
                "-loglevel",
                "error",
                str(speaker_path),
            ]
        )

    return speaker_path


def mix_speaker_tracks(
    speaker_tracks: list[Path],
    output_path: Path,
    total_duration: float,
) -> None:
    """Mix <= a few speaker tracks into one mono full-duration WAV."""
    if not speaker_tracks:
        raise RuntimeError("No speaker tracks to mix.")

    if len(speaker_tracks) == 1:
        run_cmd(
            [
                "ffmpeg",
                "-y",
                "-i",
                str(speaker_tracks[0]),
                "-ac",
                "1",
                "-ar",
                str(DEFAULT_SAMPLE_RATE),
                "-t",
                f"{total_duration:.6f}",
                "-c:a",
                "pcm_s16le",
                "-loglevel",
                "error",
                str(output_path),
            ]
        )
        return

    inputs: list[str] = []
    labels: list[str] = []
    for i, track in enumerate(speaker_tracks):
        inputs.extend(["-i", str(track)])
        labels.append(f"[{i}:a]")

    filter_complex = (
        ";".join(
            f"[{i}:a]aresample={DEFAULT_SAMPLE_RATE},aformat=channel_layouts=mono[{i}a]"
            for i in range(len(speaker_tracks))
        )
        + ";"
        + "".join(f"[{i}a]" for i in range(len(speaker_tracks)))
        + f"amix=inputs={len(speaker_tracks)}:duration=longest:normalize=0[mix]"
    )

    run_cmd(
        [
            "ffmpeg",
            "-y",
            *inputs,
            "-filter_complex",
            filter_complex,
            "-map",
            "[mix]",
            "-ac",
            "1",
            "-ar",
            str(DEFAULT_SAMPLE_RATE),
            "-t",
            f"{total_duration:.6f}",
            "-c:a",
            "pcm_s16le",
            "-loglevel",
            "error",
            str(output_path),
        ]
    )


