def process(
    srt_path: Path,
    audio_path: Path,
    speaker_dir: Path,
    output_dir: Path,
    device: str,
    reference_seconds: float,
    exaggeration: float,
    cfg_weight: float,
    temperature: float,
    min_p: float,
    top_p: float,
    repetition_penalty: float,
    max_chars: int,
    interpart_pause: float,
    fit_margin_ms: int,
    seed: int,
    video_path: Path | None,
    make_preview: bool,
    original_volume: float,
    dub_volume: float,
    use_mix_for_video: bool,
    keep_clips: bool,
    t3_model: str,
    tts_retries: int,
    min_duration_ratio: float,
    max_speedup: float,
) -> None:
    ensure_ffmpeg()

    srt_path = srt_path.expanduser().resolve()
    audio_path = audio_path.expanduser().resolve()
    speaker_dir = speaker_dir.expanduser().resolve()
    output_dir = output_dir.expanduser().resolve()

    if not srt_path.exists():
        raise FileNotFoundError(f"SRT not found: {srt_path}")
    if not audio_path.exists():
        raise FileNotFoundError(f"Original audio not found: {audio_path}")
    if not speaker_dir.exists():
        raise FileNotFoundError(f"Speaker directory not found: {speaker_dir}")

    output_dir.mkdir(parents=True, exist_ok=True)
    clips_dir = output_dir / "tts_clips"
    cue_dir = output_dir / ".cue_tracks"
    refs_dir = output_dir / "voice_references"
    clips_dir.mkdir(exist_ok=True)
    cue_dir.mkdir(exist_ok=True)
    refs_dir.mkdir(exist_ok=True)

    errors_log = output_dir / "errors.log"
    if not errors_log.exists():
        errors_log.write_text("", encoding="utf-8")

    cues = parse_srt(srt_path)
    if not cues:
        raise RuntimeError("No valid [Speaker]: subtitle cues were found in the SRT.")

    total_duration = ffprobe_duration(audio_path)

    # Clamp cues to the original source duration.
    valid_cues: list[Cue] = []
    for cue in cues:
        if cue.start >= total_duration:
            continue
        end = min(cue.end, total_duration)
        if end <= cue.start:
            continue
        valid_cues.append(
            Cue(
                index=cue.index,
                start=cue.start,
                end=end,
                speaker=cue.speaker,
                text=cue.text,
            )
        )

    cues = valid_cues

    speakers = sorted({cue.speaker for cue in cues})
    print("=" * 72)
    print("CHATTERBOX RUSSIAN DUBBER")
    print("=" * 72)
    print(f"SRT:          {srt_path}")
    print(f"Audio:        {audio_path}")
    print(f"Speaker refs: {speaker_dir}")
    print(f"Output:       {output_dir}")
    print(f"Duration:     {total_duration:.2f}s")
    print(f"Cues:         {len(cues)}")
    print(f"Speakers:     {', '.join(speakers)}")
    print(f"Device:       {device}")
    print(f"Language:     {LANGUAGE_ID}")
    print(f"CFG weight:   {cfg_weight}")
    print(f"T3 model:     {t3_model}")
    print(f"TTS retries:  {tts_retries}")
    print(f"Min duration: {min_duration_ratio:.2f}x estimate")
    print("=" * 72)

    set_global_seed(seed)

    tts = ChatterboxSpeaker(
        device=device,
        exaggeration=exaggeration,
        cfg_weight=cfg_weight,
        temperature=temperature,
        min_p=min_p,
        top_p=top_p,
        repetition_penalty=repetition_penalty,
        seed=seed,
        t3_model=t3_model,
        tts_retries=tts_retries,
        min_duration_ratio=min_duration_ratio,
    )

    cues_by_speaker: dict[str, list[Cue]] = {}
    for cue in cues:
        cues_by_speaker.setdefault(cue.speaker, []).append(cue)

    cue_files_by_speaker: dict[str, dict[int, Path]] = {}
    speaker_tracks: list[Path] = []

    try:
        for speaker in speakers:
            print(f"\n{'=' * 72}\nSPEAKER: {speaker}\n{'=' * 72}")

            reference = find_speaker_reference(
                speaker=speaker,
                speaker_dir=speaker_dir,
                reference_dir=refs_dir,
                reference_seconds=reference_seconds,
                threshold_db=DEFAULT_REFERENCE_MIN_DB,
            )
            print(f"Reference: {reference}")

            # Prepare once for the whole speaker. Chatterbox's conditioning is
            # reused across all sentences until another speaker reference is set.
            tts.prepare_reference(reference)

            cue_files: dict[int, Path] = {}
            cue_files_by_speaker[speaker] = cue_files

            for pos, cue in enumerate(
                sorted(cues_by_speaker[speaker], key=lambda c: (c.start, c.index)),
                start=1,
            ):
                print(
                    f"\n[{pos}/{len(cues_by_speaker[speaker])}] "
                    f"{cue.start:.3f} -> {cue.end:.3f} "
                    f"({cue.duration:.3f}s), {word_count(cue.text)} words"
                )
                print(f"  {cue.text}")

                raw_clip = clips_dir / f"{safe_filename(speaker)}_{cue.index:06d}_raw.wav"
                fixed_clip = cue_dir / f"{safe_filename(speaker)}_{cue.index:06d}.wav"

                try:
                    known_raw_duration: float | None = None

                    if not raw_clip.exists():
                        _, known_raw_duration = tts.generate_to_file(
                            text=cue.text,
                            reference_path=reference,
                            output_path=raw_clip,
                            max_chars=max_chars,
                            interpart_pause=interpart_pause,
                        )
                    else:
                        known_raw_duration = ffprobe_duration(raw_clip)
                        if known_raw_duration <= 0.05:
                            print("  Cached TTS clip is invalid; regenerating.")
                            try:
                                raw_clip.unlink()
                            except OSError:
                                pass
                            _, known_raw_duration = tts.generate_to_file(
                                text=cue.text,
                                reference_path=reference,
                                output_path=raw_clip,
                                max_chars=max_chars,
                                interpart_pause=interpart_pause,
                            )

                    speech_duration, delay, was_speed_adjusted = fit_and_center_clip(
                        input_wav=raw_clip,
                        output_wav=fixed_clip,
                        window_duration=cue.duration,
                        source_rate=DEFAULT_SAMPLE_RATE,
                        margin_ms=fit_margin_ms,
                        known_duration=known_raw_duration,
                        max_speedup=max_speedup,
                    )

                    if was_speed_adjusted:
                        print(
                            f"  Fitted speech: {speech_duration:.3f}s "
                            f"with FFmpeg time compression; cue={cue.duration:.3f}s"
                        )
                    else:
                        print(
                            f"  Centered speech: {speech_duration:.3f}s, "
                            f"padding each side ≈ {delay:.3f}s"
                        )

                    cue_files[cue.index] = fixed_clip

                except Exception as exc:
                    error_text = (
                        f"cue={cue.index}; speaker={cue.speaker}; "
                        f"start={cue.start:.3f}; end={cue.end:.3f}; "
                        f"error={type(exc).__name__}: {exc}"
                    )
                    print(f"  ERROR: {error_text}")
                    with errors_log.open("a", encoding="utf-8") as log:
                        log.write(error_text + "\n")

                    for bad_path in (raw_clip, fixed_clip):
                        try:
                            if bad_path.exists():
                                bad_path.unlink()
                        except OSError:
                            pass

                    # Exact-duration silence keeps the timeline aligned and lets
                    # the rest of a long dubbing job continue.
                    run_cmd(
                        [
                            "ffmpeg",
                            "-y",
                            "-f",
                            "lavfi",
                            "-i",
                            f"anullsrc=channel_layout=mono:sample_rate={DEFAULT_SAMPLE_RATE}",
                            "-t",
                            f"{cue.duration:.6f}",
                            "-c:a",
                            "pcm_s16le",
                            "-loglevel",
                            "error",
                            str(fixed_clip),
                        ]
                    )
                    cue_files[cue.index] = fixed_clip

                gc.collect()
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()

                if not keep_clips:
                    # Raw clips are only cache material; voice references and
                    # final speaker tracks remain.
                    try:
                        raw_clip.unlink()
                    except OSError:
                        pass

            speaker_track = make_speaker_track(
                speaker=speaker,
                cues=cues_by_speaker[speaker],
                cue_files=cue_files,
                total_duration=total_duration,
                speaker_output_dir=output_dir / "speaker_dub_tracks",
            )
            speaker_tracks.append(speaker_track)
            print(f"Speaker track: {speaker_track}")

        # Mix all Russian speakers into a single clean dialogue track.
        dub_path = output_dir / "russian_dub.wav"
        mix_speaker_tracks(
            speaker_tracks=speaker_tracks,
            output_path=dub_path,
            total_duration=total_duration,
        )
        print(f"\nRussian dub track: {dub_path}")

        mixed_path = None
        if make_preview or use_mix_for_video:
            mixed_path = output_dir / "russian_dub_mixed_with_original.wav"
            make_preview_mix(
                original_audio=audio_path,
                dub_audio=dub_path,
                output_path=mixed_path,
                original_volume=original_volume,
                dub_volume=dub_volume,
            )
            print(
                f"Mixed track: {mixed_path} "
                f"(original={original_volume:.3f}, dub={dub_volume:.3f})"
            )

        if video_path:
            video_path = video_path.expanduser().resolve()
            if not video_path.exists():
                raise FileNotFoundError(f"Video not found: {video_path}")

            out_video = output_dir / (
                f"{video_path.stem}_ru_dub_mixed.mp4"
                if use_mix_for_video
                else f"{video_path.stem}_ru_dub.mp4"
            )
            mux_audio_into_video(
                video_path=video_path,
                dub_audio=mixed_path if use_mix_for_video and mixed_path else dub_path,
                output_video=out_video,
            )
            print(f"Dubbed video: {out_video}")

        if errors_log.exists() and errors_log.stat().st_size > 0:
            print(f"WARNING: some cues were replaced with silence. See: {errors_log}")

    finally:
        # Avoid retaining the large model between separate Python operations.
        try:
            del tts.model
        except Exception:
            pass
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

        # Cue tracks are intermediate and can be deleted after the final mix.
        shutil.rmtree(cue_dir, ignore_errors=True)


