def make_preview_mix(
    original_audio: Path,
    dub_audio: Path,
    output_path: Path,
    original_volume: float,
    dub_volume: float = 1.0,
) -> None:
    """
    Mix the original audio quietly under the Russian dub.

    The original track is intentionally kept audible so that music, ambience,
    room tone and sound effects remain present. This does NOT remove the
    original dialogue; the original voice will remain faintly audible.

    The dub is placed at full/near-full level by default, while the original
    can be reduced with --original-volume.
    """
    if original_volume < 0 or dub_volume < 0:
        raise ValueError("Audio volumes must be >= 0")

    # Force the original to stereo. The generated Russian dialogue is mono;
    # duplicating it to stereo makes the overlay sound natural while retaining
    # the original stereo image when the source is stereo.
    filter_complex = (
        f"[0:a]aresample={DEFAULT_SAMPLE_RATE},"
        f"aformat=sample_fmts=fltp:channel_layouts=stereo,"
        f"volume={original_volume:.6f}[orig];"
        f"[1:a]aresample={DEFAULT_SAMPLE_RATE},"
        f"aformat=sample_fmts=fltp:channel_layouts=mono,"
        f"volume={dub_volume:.6f},"
        f"pan=stereo|c0=c0|c1=c0[dub];"
        "[orig][dub]amix=inputs=2:duration=first:dropout_transition=0:"
        "normalize=0,alimiter=limit=0.97:attack=5:release=50[mix]"
    )

    run_cmd(
        [
            "ffmpeg",
            "-y",
            "-i",
            str(original_audio),
            "-i",
            str(dub_audio),
            "-filter_complex",
            filter_complex,
            "-map",
            "[mix]",
            "-ar",
            str(DEFAULT_SAMPLE_RATE),
            "-ac",
            "2",
            "-c:a",
            "pcm_s16le",
            "-loglevel",
            "error",
            str(output_path),
        ]
    )


def mux_audio_into_video(
    video_path: Path,
    dub_audio: Path,
    output_video: Path,
) -> None:
    run_cmd(
        [
            "ffmpeg",
            "-y",
            "-i",
            str(video_path),
            "-i",
            str(dub_audio),
            "-map",
            "0:v:0",
            "-map",
            "1:a:0",
            "-c:v",
            "copy",
            "-c:a",
            "aac",
            "-b:a",
            "192k",
            "-shortest",
            "-loglevel",
            "error",
            str(output_video),
        ]
    )


