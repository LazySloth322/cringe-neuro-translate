def choose_device(requested: str | None) -> str:
    if requested:
        if requested == "cuda" and not torch.cuda.is_available():
            raise RuntimeError("--device cuda requested, but torch.cuda.is_available() is False.")
        if requested == "mps" and not torch.backends.mps.is_available():
            raise RuntimeError("--device mps requested, but MPS is not available.")
        return requested

    if torch.cuda.is_available():
        return "cuda"
    if torch.backends.mps.is_available():
        return "mps"
    return "cpu"


def main() -> None:
    parser = build_argparser()
    args = parser.parse_args()

    srt_path = Path(args.srt).expanduser().resolve()
    audio_path = Path(args.audio).expanduser().resolve()

    if args.speaker_dir:
        speaker_dir = Path(args.speaker_dir).expanduser().resolve()
    else:
        # The typical structure is:
        # output.srt
        # speaker_outputs/Speaker_0.mp3
        # so first look next to the SRT, then in the current directory.
        candidates = [
            srt_path.parent / "speaker_outputs",
            srt_path.parent.parent / "speaker_outputs",
            Path("speaker_outputs").resolve(),
        ]
        speaker_dir = next(
            (p for p in candidates if p.exists()),
            candidates[0],
        )

    output_dir = (
        Path(args.output_dir).expanduser().resolve()
        if args.output_dir
        else default_output_dir(srt_path)
    )

    if args.reference_seconds <= 0:
        parser.error("--reference-seconds must be > 0")
    if args.max_chars < 40:
        parser.error("--max-chars should be >= 40")
    if args.interpart_pause < 0:
        parser.error("--interpart-pause must be >= 0")
    if args.fit_margin_ms < 0:
        parser.error("--fit-margin-ms must be >= 0")
    if args.tts_retries < 1 or args.tts_retries > 3:
        parser.error("--tts-retries must be between 1 and 3")
    if not 0.1 <= args.min_duration_ratio <= 1.0:
        parser.error("--min-duration-ratio must be between 0.1 and 1.0")
    if args.max_speedup_warning < 1.0:
        parser.error("--max-speedup-warning must be >= 1.0")
    if not 0.0 <= args.original_volume <= 2.0:
        parser.error("--original-volume must be between 0 and 2")
    if not 0.0 <= args.dub_volume <= 2.0:
        parser.error("--dub-volume must be between 0 and 2")
    if args.mix_for_video and not args.video:
        parser.error("--mix-for-video requires --video")

    device = choose_device(args.device)

    process(
        srt_path=srt_path,
        audio_path=audio_path,
        speaker_dir=speaker_dir,
        output_dir=output_dir,
        device=device,
        reference_seconds=args.reference_seconds,
        exaggeration=args.exaggeration,
        cfg_weight=args.cfg_weight,
        temperature=args.temperature,
        min_p=args.min_p,
        top_p=args.top_p,
        repetition_penalty=args.repetition_penalty,
        max_chars=args.max_chars,
        interpart_pause=args.interpart_pause,
        fit_margin_ms=args.fit_margin_ms,
        seed=args.seed,
        video_path=Path(args.video).expanduser().resolve() if args.video else None,
        make_preview=(args.preview_original or args.mix_original),
        original_volume=args.original_volume,
        dub_volume=args.dub_volume,
        # --mix-original is the user-facing switch for the normal workflow:
        # create the mix and, when --video is present, put that mix into the MP4.
        # --mix-for-video is retained as an explicit alias for clarity.
        use_mix_for_video=(args.mix_original or args.mix_for_video),
        keep_clips=args.keep_clips,
        t3_model=args.t3_model,
        tts_retries=args.tts_retries,
        min_duration_ratio=args.min_duration_ratio,
        max_speedup=args.max_speedup_warning,
    )


if __name__ == "__main__":
    main()
