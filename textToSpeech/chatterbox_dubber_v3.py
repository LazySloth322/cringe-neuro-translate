def atempo_filter_for_speed(speed: float) -> str:
    """
    Build an FFmpeg atempo chain for arbitrary positive speed factors.

    FFmpeg's atempo accepts 0.5..2.0 per filter. Chaining handles larger/smaller
    factors safely.
    """
    if speed <= 0:
        raise ValueError("speed must be positive")

    factors: list[float] = []
    remaining = speed

    while remaining > 2.0:
        factors.append(2.0)
        remaining /= 2.0

    while remaining < 0.5:
        factors.append(0.5)
        remaining /= 0.5

    factors.append(remaining)
    return ",".join(f"atempo={factor:.8f}" for factor in factors)


def fit_and_center_clip(
    input_wav: Path,
    output_wav: Path,
    window_duration: float,
    source_rate: int = DEFAULT_SAMPLE_RATE,
    margin_ms: int = DEFAULT_FIT_MARGIN_MS,
    known_duration: float | None = None,
    max_speedup: float = DEFAULT_MAX_SPEEDUP,
) -> tuple[float, float, bool]:
    """
    Return (final_speech_duration, center_delay_seconds, was_speed_adjusted).

    The output is EXACTLY window_duration seconds, containing the TTS speech
    centered when it is shorter than the available window.
    """
    clip_duration = known_duration if known_duration is not None else ffprobe_duration(input_wav)
    if clip_duration <= 0.01:
        raise RuntimeError(f"Generated TTS clip is empty: {input_wav}")

    # Leave a very small guard margin so no last phoneme sits exactly on a cue
    # boundary.
    target_duration = max(
        0.05,
        window_duration - (margin_ms / 1000.0),
    )

    was_speed_adjusted = False
    fitted_wav = output_wav.with_name(output_wav.stem + "_fitted.wav")

    if clip_duration > target_duration:
        speed = clip_duration / target_duration
        if speed > max_speedup:
            print(
                f"  WARNING: TTS is {speed:.2f}x longer than the cue. "
                "Strong time-compression may sound unnatural; "
                "consider more aggressive text compression or longer subtitle windows."
            )
        tempo_filter = atempo_filter_for_speed(speed)
        run_cmd(
            [
                "ffmpeg",
                "-y",
                "-i",
                str(input_wav),
                "-af",
                tempo_filter,
                "-ac",
                "1",
                "-ar",
                str(source_rate),
                "-c:a",
                "pcm_s16le",
                "-loglevel",
                "error",
                str(fitted_wav),
            ]
        )
        clip_for_padding = fitted_wav
        clip_duration = ffprobe_duration(fitted_wav)
        was_speed_adjusted = True
    else:
        clip_for_padding = input_wav

    # Center shorter speech in the original cue window. If the clip had to be
    # sped up, it already nearly fills the window and receives a tiny centered
    # safety margin.
    delay = max(0.0, (window_duration - clip_duration) / 2.0)

    # The final cue file is exactly the subtitle duration.
    delay_ms = int(round(delay * 1000))

    run_cmd(
        [
            "ffmpeg",
            "-y",
            "-i",
            str(clip_for_padding),
            "-af",
            f"adelay={delay_ms}:all=1,apad,atrim=0:{window_duration:.6f},"
            f"asetpts=N/SR/TB",
            "-ac",
            "1",
            "-ar",
            str(source_rate),
            "-t",
            f"{window_duration:.6f}",
            "-c:a",
            "pcm_s16le",
            "-loglevel",
            "error",
            str(output_wav),
        ]
    )

    if fitted_wav.exists():
        fitted_wav.unlink()

    return clip_duration, delay, was_speed_adjusted


