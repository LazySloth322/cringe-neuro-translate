def run_cmd(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    """Run a command and return a completed process with readable errors."""
    try:
        result = subprocess.run(
            cmd,
            check=check,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            f"Executable not found: {cmd[0]!r}. Install FFmpeg and make sure "
            "ffmpeg/ffprobe are available in PATH."
        ) from exc

    if check and result.returncode != 0:
        details = (result.stderr or result.stdout or "").strip()
        raise RuntimeError(
            f"Command failed with exit code {result.returncode}:\n"
            f"{' '.join(map(str, cmd))}\n\n{details}"
        )

    return result


def ensure_ffmpeg() -> None:
    missing = [name for name in ("ffmpeg", "ffprobe") if shutil.which(name) is None]
    if missing:
        raise RuntimeError(
            "Missing required executables: " + ", ".join(missing) + ". "
            "Install FFmpeg and add it to PATH."
        )


def wav_duration(path: Path) -> float | None:
    """Read WAV duration directly from frame count when possible."""
    try:
        with wave.open(str(path), "rb") as wf:
            frames = wf.getnframes()
            rate = wf.getframerate()
            if frames > 0 and rate > 0:
                return frames / float(rate)
    except (wave.Error, EOFError, OSError):
        return None
    return None


def ffprobe_duration(path: Path) -> float:
    """Robust duration reader; WAV uses Python's wave module first."""
    path = Path(path)

    # This completely avoids the ffprobe=N/A failure for valid PCM WAV files.
    if path.suffix.lower() in {".wav", ".wave"}:
        duration = wav_duration(path)
        if duration is not None and duration > 0:
            return duration

    queries = [
        [
            "ffprobe", "-v", "error",
            "-show_entries", "format=duration",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        [
            "ffprobe", "-v", "error",
            "-select_streams", "a:0",
            "-show_entries", "stream=duration",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        [
            "ffprobe", "-v", "error",
            "-select_streams", "a:0",
            "-show_entries", "stream=nb_frames,sample_rate",
            "-of", "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
    ]

    for cmd in queries:
        result = run_cmd(cmd, check=False)
        values = [line.strip() for line in (result.stdout or "").splitlines() if line.strip()]

        if len(values) == 1 and values[0] != "N/A":
            try:
                duration = float(values[0])
                if math.isfinite(duration) and duration > 0:
                    return duration
            except ValueError:
                pass

        if len(values) >= 2:
            try:
                frames = int(values[0])
                sample_rate = int(values[1])
                if frames > 0 and sample_rate > 0:
                    return frames / float(sample_rate)
            except ValueError:
                pass

    raise RuntimeError(f"Could not determine audio duration of {path}")

def ffprobe_channels(path: Path) -> int:
    result = run_cmd(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "a:0",
            "-show_entries",
            "stream=channels",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(path),
        ]
    )
    try:
        return int(result.stdout.strip())
    except ValueError:
        return 1


def safe_filename(name: str) -> str:
    safe = re.sub(r"[^0-9A-Za-zА-Яа-я._-]+", "_", name)
    return safe.strip("_") or "Speaker"


def set_global_seed(seed: int) -> None:
    if seed == 0:
        return

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)


# ---------------------------------------------------------------------------
# SRT parsing
# ---------------------------------------------------------------------------

TIME_RE = re.compile(
    r"(?P<start>\d{2}:\d{2}:\d{2},\d{3})\s*-->\s*"
    r"(?P<end>\d{2}:\d{2}:\d{2},\d{3})"
)

SPEAKER_RE = re.compile(
    r"^\s*\[(?P<speaker>[^\]]+)\]\s*:\s*(?P<text>.*)$",
    re.DOTALL,
)


def parse_srt_time(value: str) -> float:
    h, m, sec_ms = value.split(":")
    s, ms = sec_ms.split(",")
    return (
        int(h) * 3600
        + int(m) * 60
        + int(s)
        + int(ms) / 1000.0
    )


def parse_srt(path: Path) -> list[Cue]:
    content = path.read_text(encoding="utf-8-sig")
    blocks = re.split(r"\n\s*\n", content.strip())

    cues: list[Cue] = []

    for block in blocks:
        lines = block.splitlines()
        if len(lines) < 3:
            continue

        try:
            index = int(lines[0].strip())
        except ValueError:
            continue

        time_match = TIME_RE.search(lines[1])
        if not time_match:
            continue

        start = parse_srt_time(time_match.group("start"))
        end = parse_srt_time(time_match.group("end"))
        if end <= start:
            continue

        text = "\n".join(lines[2:]).strip()
        speaker_match = SPEAKER_RE.match(text)
        if not speaker_match:
            # The dubbing pipeline expects speaker labels. Keeping the cue
            # with a visible Unknown Speaker is safer than silently dropping it.
            speaker = "Unknown Speaker"
        else:
            speaker = speaker_match.group("speaker").strip()
            text = speaker_match.group("text").strip()

        text = normalize_text(text)
        if not text:
            continue

        cues.append(
            Cue(
                index=index,
                start=start,
                end=end,
                speaker=speaker,
                text=text,
            )
        )

    cues.sort(key=lambda c: (c.start, c.end, c.index))
    return cues


def normalize_text(text: str) -> str:
    text = text.replace("ё", "е").replace("Ё", "Е")
    
    text = re.sub(r"\s+", " ", text)
    return text.strip()


